/* 언어 결정
   ---------------------------------------------------------------
   한국어·영어 페이지는 파일이 따로 있다. about.html(베트남어) 옆에
   about.ko.html / about.en.html 이 함께 구워지고, 그 파일들은 머리에
   window.MK_FORCE_LANG 을 박아 둔다. 주소마다 언어가 하나로 정해져야
   검색엔진이 hreflang 으로 세 판을 묶을 수 있기 때문이다.

   기본형(.html)은 예전처럼 localStorage 를 따른다. 한국어로 보던 사람이
   북마크한 주소로 돌아왔을 때 갑자기 베트남어가 되지 않게 하려는 것이고,
   크롤러는 localStorage 가 비어 있으므로 항상 베트남어를 본다. */
/* 언어별 호스트 (서브도메인 운영).
   vn.makenov.com = 베트남어(루트 파일), kr.makenov.com = 한국어(ko/), en.makenov.com = 영어(en/).
   Nginx 가 호스트별로 언어 폴더를 먼저 찾아 주므로(kr 호스트에서 /products.html → ko/products.html)
   주소에는 언어 폴더가 드러나지 않는다. 이 호스트 중 하나로 들어오면 언어는 호스트가 정한다. */
const MK_HOSTS = { vi:'vn.makenov.com', ko:'kr.makenov.com', en:'en.makenov.com' };
const MK_HOST_LANG = (function(){
  const h = location.hostname;
  for (const l in MK_HOSTS) if (MK_HOSTS[l] === h) return l;
  return null;
})();
if (MK_HOST_LANG) window.MK_FORCE_LANG = MK_HOST_LANG;
let MK_LANG = window.MK_FORCE_LANG || localStorage.getItem('mk_lang') || 'vi';
function t(key){ return (I18N[MK_LANG] && I18N[MK_LANG][key]) || I18N.vi[key] || key; }

/* 언어판이 있는 페이지 목록. 여기 있는 것만 .ko.html / .en.html 이 실제로 구워진다.
   (maker.html 은 한국어 전용, mypage·admin 은 비공개라 언어판이 없다) */
const MK_LANG_PAGES = ['index.html','products.html','directory.html','companies.html','columns.html',
                       'about.html','guide.html','support.html'];

/* 사이트 루트의 경로.
   모든 페이지의 <base> 가 루트를 가리키므로 baseURI 에서 그대로 얻는다.
   (GitHub Pages 처럼 하위 경로에 올라가도 맞는다) */
function mkSiteRoot(){
  return new URL(document.baseURI).pathname.replace(/[^/]*$/, '');
}

/* 네비게이션 링크를 지금 언어판으로 맞춘다.
   한국어 페이지에서 헤더 '제품'이 directory.html(베트남어)로 가면
   한국어 페이지들로 들어오는 내부 링크가 하나도 생기지 않는다.
   문서 안의 상대경로는 <base> 덕분에 루트 기준이라 앞에 언어 폴더만 붙이면 된다. */
function mkUrl(rel){
  const l = window.MK_FORCE_LANG;
  if(MK_HOST_LANG) return rel;                       // 서브도메인에선 호스트가 언어라 경로에 안 붙인다
  if(!l || l === 'vi') return rel;
  const m = String(rel).match(/^([^#?]+)([#?].*)?$/);
  if(!m || MK_LANG_PAGES.indexOf(m[1]) < 0) return rel;
  return l + '/' + m[1] + (m[2] || '');
}

/* 제품·칼럼·공급사 문서의 정식 주소.
   구워진 문서면 products/p0.html 같은 정식 주소로, 아직 안 구워졌으면
   예전처럼 product.html?id=p0 뷰어로 보낸다(파일이 없으면 404 이므로).
   목록은 bake.js 가 assets/js/baked.js 로 내보낸다. */
function mkDocUrl(kind, id){
  const B = window.MK_BAKED;
  const viewer = { product:'product.html', company:'company.html', column:'column.html' }[kind]
    + '?id=' + encodeURIComponent(id);
  if(!B) return viewer;
  /* 구운 문서는 세 언어가 모두 있으므로 지금 언어판으로 보낸다 */
  const l = window.MK_FORCE_LANG;
  const doc = rel => (MK_HOST_LANG || !l || l === 'vi') ? rel : l + '/' + rel;
  if(kind === 'product') return B.products.indexOf(id) < 0 ? viewer : doc('products/' + id + '.html');
  if(kind === 'company') return B.companies.indexOf(id) < 0 ? viewer : doc('companies/' + id + '.html');
  if(kind === 'column'){
    const slug = B.columns && B.columns[id];
    return slug ? doc('columns/' + slug + '.html') : viewer;
  }
  return viewer;
}

/* 지금 주소의 다른 언어판 경로. 없으면 null */
function mkLangHref(l){
  /* 이 페이지에 언어판이 있는지는 head 의 hreflang 링크로 판단한다.
     링크의 href 는 절대주소(확정 도메인 기준)라 이동에는 쓰지 않고,
     존재 여부만 본다. 실제 이동 경로는 파일명 규칙으로 만든다. */
  const alt = document.querySelector('link[rel="alternate"][hreflang="' + l + '"]');
  /* 서브도메인 운영: 모든 페이지가 세 호스트에 다 있다(언어 중립 페이지도 복사됨).
     hreflang 링크가 있으면 그 절대주소로, 없으면 같은 경로를 다른 호스트에서 연다 */
  if(MK_HOST_LANG){
    if(l === MK_HOST_LANG) return null;               // 지금 호스트의 언어면 이동 없음
    if(alt){
      try{
        const u = new URL(alt.getAttribute('href'), location.href);
        if(u.hostname !== location.hostname){
          u.search = location.search;
          u.searchParams.set('lang', l);
          u.hash = location.hash;
          return u.href;
        }
      }catch(e){}
    }
    let rel = location.pathname; if(rel === '' || /\/$/.test(rel)) rel += 'index.html';
    const u = new URL('https://' + MK_HOSTS[l] + rel.replace(/^\/(ko|en)\//, '/'));
    u.search = location.search;
    u.searchParams.set('lang', l);
    u.hash = location.hash;
    return u.href;
  }
  if(!alt) return null;
  const root = mkSiteRoot();
  let rel = location.pathname.slice(root.length);
  if(rel === '' || /\/$/.test(rel)) rel += 'index.html';
  rel = rel.replace(/^(ko|en)\//, '');                 // 기본형(베트남어)으로 되돌리고
  if(l !== 'vi') rel = l + '/' + rel;
  return root + rel + location.search + location.hash;
}

function setLang(l){
  localStorage.setItem('mk_lang', l);
  const href = mkLangHref(l);
  if(href && href !== location.pathname + location.search + location.hash && href !== location.href){
    location.href = href;                              // 언어판이 있으면 그 주소로 간다
    return;
  }
  MK_LANG = l;
  document.documentElement.lang = l;
  applyI18n();
  document.dispatchEvent(new CustomEvent('mk:lang'));
}
function applyI18n(root){
  (root||document).querySelectorAll('[data-i18n]').forEach(el=>{ el.textContent = t(el.dataset.i18n); });
  (root||document).querySelectorAll('[data-i18n-ph]').forEach(el=>{ el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('.mk-lang button, .ft-lang button').forEach(b=>b.classList.toggle('on', b.dataset.lang===MK_LANG));
}
/* localized field helper: product fields stored as {vi,ko,en} */
function L(field){ if(field==null) return ''; if(typeof field==='string') return field; return field[MK_LANG] || field.vi || field.en || field.ko || ''; }

